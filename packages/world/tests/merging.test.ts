/**
 * Bringing work across sessions: `ws.merge` (a whole session's
 * committed work), `ws.revert` and `ws.cherryPick` (one commit's
 * change, undone or brought). One three-way engine and one set of
 * rules: files merge as text, with markers where both sides changed the
 * same lines, and the session's own state takes ours.
 */

import { Memory } from '@agex-ts/kvgit/backends/memory'
import { describe, expect, it } from 'vitest'
import {
  MERGE_TOOL,
  ReadOnlyError,
  Store,
  UnknownRefError,
  UnknownSessionError,
  type Workspace,
} from '../src/index'

const enc = new TextEncoder()

async function open(): Promise<Workspace> {
  return (await Store.open(new Memory())).open('main')
}

const put = (ws: Workspace, path: string, text: string) => ws.files.fs.write(path, enc.encode(text))
const read = (ws: Workspace, path: string) => ws.files.readText(path)

describe('ws.merge', () => {
  it("brings a fork's work home, as a merge commit the agent's git records", async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: true, conflicts: [], autoMerged: ['/workspace/b.txt'] })
    expect(ws.uncommitted).toBe(false)
    expect(out.commit).toBe(await ws.index.head())
    expect(ws.head).not.toBe(out.commit)
    expect(await read(ws, 'b.txt')).toBe('worker\n')
    const merge = await ws.store.repo.getCommit(out.commit as string)
    expect(merge.info).toMatchObject({ tool: MERGE_TOOL, source: 'worker' })
    expect(merge.parents).toHaveLength(2)
    await fork.close()
    await ws.close()
  })

  it('unions disjoint work from both sides', async () => {
    const ws = await open()
    await ws.terminal('echo one > a.txt')
    const fork = await ws.fork('worker')
    await fork.terminal('echo two > b.txt')
    await ws.terminal('echo three > c.txt')
    expect((await ws.merge('worker')).merged).toBe(true)
    expect(await read(ws, 'b.txt')).toBe('two\n')
    expect(await read(ws, 'c.txt')).toBe('three\n')
    await fork.close()
    await ws.close()
  })

  it('lands overlapping lines with markers, outstanding until they go', async () => {
    const ws = await open()
    await put(ws, '/workspace/doc.txt', 'a\nb\n')
    await ws.commit()
    const fork = await ws.fork('worker')
    await put(fork, '/workspace/doc.txt', 'a\nFORK\n')
    await fork.commit()
    await put(ws, '/workspace/doc.txt', 'a\nMAIN\n')
    await ws.commit()
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: true, conflicts: ['/workspace/doc.txt'], autoMerged: [] })
    expect(await read(ws, 'doc.txt')).toContain('<<<<<<< ')
    expect(await ws.index.status()).toMatchObject({
      mergeSource: 'worker',
      mergeUnresolved: ['/workspace/doc.txt'],
      staged: [],
      unstaged: [],
    })
    await put(ws, '/workspace/doc.txt', 'a\nBOTH\n')
    await ws.index.commit('resolved')
    expect(await ws.index.status()).toMatchObject({ mergeSource: null, mergeUnresolved: [] })
    await fork.close()
    await ws.close()
  })

  it('ends an outstanding merge on any commit that takes the markers away', async () => {
    const ws = await open()
    await put(ws, '/workspace/doc.txt', 'a\nb\n')
    await ws.commit()
    const fork = await ws.fork('worker')
    await put(fork, '/workspace/doc.txt', 'a\nFORK\n')
    await fork.commit()
    await put(ws, '/workspace/doc.txt', 'a\nMAIN\n')
    await ws.commit()
    await ws.merge('worker')
    expect((await ws.index.status()).mergeSource).toBe('worker')
    await put(ws, '/workspace/doc.txt', 'a\nBOTH\n')
    await ws.commit({ tool: 'turn' })
    expect((await ws.index.status()).mergeSource).toBeNull()
    await fork.close()
    await ws.close()
  })

  it('holds the merge until every marked path is resolved, not just committed', async () => {
    const ws = await open()
    await put(ws, '/workspace/one.txt', 'a\nb\n')
    await put(ws, '/workspace/two.txt', 'a\nb\n')
    await ws.index.commit('base')
    const fork = await ws.fork('worker')
    await put(fork, '/workspace/one.txt', 'a\nFORK\n')
    await put(fork, '/workspace/two.txt', 'a\nFORK\n')
    await fork.index.commit('fork work')
    await put(ws, '/workspace/one.txt', 'a\nMAIN\n')
    await put(ws, '/workspace/two.txt', 'a\nMAIN\n')
    await ws.index.commit('main work')
    const out = await ws.merge('worker')
    expect([...out.conflicts].sort()).toEqual(['/workspace/one.txt', '/workspace/two.txt'])
    await put(ws, '/workspace/one.txt', 'a\nBOTH\n')
    const marked = await read(ws, 'two.txt')
    await put(ws, '/workspace/two.txt', `${marked}still working\n`)
    await ws.index.commit('half resolved')
    expect((await ws.index.log())[0]?.info?.files).toEqual([
      '/workspace/one.txt',
      '/workspace/two.txt',
    ])
    expect(await ws.index.status()).toMatchObject({
      mergeSource: 'worker',
      mergeUnresolved: ['/workspace/two.txt'],
    })
    await put(ws, '/workspace/two.txt', 'a\nBOTH\n')
    await ws.index.commit('resolved')
    expect((await ws.index.status()).mergeSource).toBeNull()
    await fork.close()
    await ws.close()
  })

  it('is aborted back to where it landed, keeping the merge in history', async () => {
    const ws = await open()
    await put(ws, '/workspace/doc.txt', 'a\nb\n')
    await ws.index.commit('base')
    const fork = await ws.fork('worker')
    await put(fork, '/workspace/doc.txt', 'a\nFORK\n')
    await fork.index.commit('fork')
    await put(ws, '/workspace/doc.txt', 'a\nMAIN\n')
    const mine = await ws.index.commit('main')
    const out = await ws.merge('worker')
    expect(await ws.index.abortMerge()).toEqual({ source: 'worker', commit: mine })
    expect(await read(ws, 'doc.txt')).toBe('a\nMAIN\n')
    expect(await ws.index.status()).toMatchObject({ mergeSource: null, staged: [], unstaged: [] })
    expect((await ws.log({ kind: 'all' })).some((c) => c.hash === out.commit)).toBe(true)
    await expect(ws.index.abortMerge()).rejects.toThrow('no merge to abort')
    await fork.close()
    await ws.close()
  })

  it("doesn't count markers a side already held", async () => {
    const ws = await open()
    await put(ws, '/workspace/notes.md', 'resolve it:\n<<<<<<< HEAD\nours\n=======\n')
    await ws.index.commit('notes')
    const fork = await ws.fork('worker')
    await fork.files.fs.write('/workspace/later.md', enc.encode('see <<<<<<< HEAD for details\n'))
    await fork.index.commit('worker work')
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: true, conflicts: [] })
    expect(out.autoMerged).toContain('/workspace/later.md')
    expect((await ws.index.status()).mergeSource).toBeNull()
    await fork.close()
    await ws.close()
  })

  it('sizes a merged file by its merged bytes, in the one commit', async () => {
    const ws = await open()
    await put(ws, '/workspace/doc.txt', 'a\nb\n')
    await ws.commit()
    const fork = await ws.fork('worker')
    await put(fork, '/workspace/doc.txt', 'a\nb\nfork\n')
    await fork.commit()
    await put(ws, '/workspace/doc.txt', 'main\na\nb\n')
    await ws.commit()
    const out = await ws.merge('worker')
    expect(out.conflicts).toEqual([])
    const body = await ws.files.read('doc.txt')
    expect(new TextDecoder().decode(body)).toBe('main\na\nb\nfork\n')
    expect((await ws.files.fs.stat('/workspace/doc.txt')).size).toBe(body.length)
    await fork.close()
    await ws.close()
  })

  it('keeps the surviving record of a file deleted on one side, sized to the markers', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\ntwo\nthree\n')
    const fork = await ws.fork('worker')
    await fork.files.fs.remove('/workspace/a.txt')
    await fork.commit()
    await ws.files.write('a.txt', 'one\nEDITED\nthree\n')
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: true, conflicts: ['/workspace/a.txt'] })
    const body = await ws.files.read('a.txt')
    expect(new TextDecoder().decode(body)).toContain('<<<<<<< ')
    expect((await ws.files.fs.stat('/workspace/a.txt')).size).toBe(body.length)
    await fork.close()
    await ws.close()
  })

  it('refuses a file on one side made a directory on the other, changing nothing', async () => {
    const ws = await open()
    await ws.terminal('echo file > x')
    const fork = await ws.fork('worker')
    await ws.terminal('echo more >> x')
    await fork.terminal('rm x && mkdir x && echo hi > x/inner.txt')
    const before = ws.head
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: false, commit: null })
    expect(out.conflicts).toContain('/workspace/x')
    expect(ws.head).toBe(before)
    await fork.close()
    await ws.close()
  })

  it('brings files only: the cache and the conversation stay ours', async () => {
    const ws = await open()
    ws.cache.set('k', 'base')
    await ws.commit()
    const fork = await ws.fork('worker')
    ws.cache.set('k', 'main')
    await ws.commit()
    fork.cache.set('k', 'worker')
    fork.cache.set('theirs', 'only')
    await fork.commit()
    await fork.terminal('echo two > b.txt')
    const out = await ws.merge('worker')
    expect(out).toMatchObject({ merged: true, conflicts: [] })
    expect(await ws.cache.get('k')).toBe('main')
    expect(await ws.cache.has('theirs')).toBe(false)
    expect(await read(ws, 'b.txt')).toBe('two\n')
    await fork.close()
    await ws.close()
  })

  it("merges a source at its agent's last commit, not its later framework commits", async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    await ws.index.commit('base')
    const fork = await ws.fork('worker')
    await fork.files.write('done.txt', 'done\n')
    await fork.index.commit('done')
    const agentHead = await fork.index.head()
    fork.cache.set('scratch', "the delegate's own")
    await fork.commit()
    expect(fork.head).not.toBe(agentHead)
    expect((await ws.merge('worker')).merged).toBe(true)
    expect(await read(ws, 'done.txt')).toBe('done\n')
    expect(await ws.cache.has('scratch')).toBe(false)
    await fork.close()
    await ws.close()
  })

  it('takes our own index, head and tags, never the source', async () => {
    const ws = await open()
    await put(ws, '/workspace/a.txt', 'base')
    await ws.commit()
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    await fork.index.commit('worker work')
    await fork.index.tags.add('theirs')
    await put(ws, '/workspace/a.txt', 'main')
    await ws.index.commit('main work')
    const out = await ws.merge('worker')
    expect(out.merged).toBe(true)
    expect(await ws.index.head()).toBe(out.commit)
    expect((await ws.index.log()).map((c) => c.info?.message ?? null)).toEqual([null, 'main work'])
    expect(await ws.index.tags.list()).toEqual({})
    await fork.close()
    await ws.close()
  })

  it('merges a session that never used ws-git at its latest commit', async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    expect(await fork.index.head()).toBeNull()
    expect((await ws.merge('worker')).merged).toBe(true)
    expect(await read(ws, 'b.txt')).toBe('worker\n')
    await fork.close()
    await ws.close()
  })

  it('commits its own record, leaving a clean session for the next merge', async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    await ws.index.commit('base')
    const first = await ws.fork('one')
    const second = await ws.fork('two')
    await first.terminal('echo one > one.txt')
    await first.index.commit('one')
    await second.terminal('echo two > two.txt')
    await second.index.commit('two')
    const out = await ws.merge('one')
    expect(ws.uncommitted).toBe(false)
    expect((await ws.index.log()).some((c) => c.hash === out.commit)).toBe(true)
    expect((await ws.merge('two')).merged).toBe(true)
    expect(ws.uncommitted).toBe(false)
    await first.close()
    await second.close()
    await ws.close()
  })

  it('is refused into itself, from no session, frozen, or with changes pending', async () => {
    const ws = await open()
    await expect(ws.merge('main')).rejects.toThrow('into itself')
    await expect(ws.merge('nope')).rejects.toThrow(UnknownSessionError)
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    await put(ws, '/workspace/pending.txt', 'uncommitted')
    await expect(ws.merge('worker')).rejects.toThrow('ws.commit')
    expect(ws.uncommitted).toBe(true)
    expect(await ws.files.exists('b.txt')).toBe(false)
    await ws.commit()
    expect((await ws.merge('worker')).merged).toBe(true)
    await ws.tags.add('v1')
    const snap = await ws.tags.at('v1')
    await expect(snap.merge('worker')).rejects.toThrow(ReadOnlyError)
    await fork.close()
    await ws.close()
  })

  it("is refused over the agent's uncommitted work, until it lands", async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    await ws.index.commit('base')
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    await fork.index.commit('worker work')
    await ws.terminal('echo mine > mine.txt')
    expect(ws.uncommitted).toBe(false)
    const refused = await ws.merge('worker').catch((e: Error) => e.message)
    expect(refused).toContain('ws-git commit')
    expect(refused).toContain('ws-git checkout')
    await ws.index.commit('mine')
    expect((await ws.merge('worker')).merged).toBe(true)
    await fork.close()
    await ws.close()
  })

  it('is refused over an open index before the first agent commit', async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    const fork = await ws.fork('worker')
    await fork.terminal('echo worker > b.txt')
    expect((await ws.merge('worker')).merged).toBe(true)
    await ws.terminal('echo more > c.txt')
    await ws.index.stage(['/workspace/c.txt'])
    const second = await ws.fork('two')
    await second.terminal('echo two > d.txt')
    await expect(ws.merge('two')).rejects.toThrow('uncommitted ws-git work')
    await second.close()
    await fork.close()
    await ws.close()
  })

  it('is refused while the source has work past its last agent commit', async () => {
    const ws = await open()
    await ws.terminal('echo base > a.txt')
    await ws.index.commit('base')
    const fork = await ws.fork('worker')
    await fork.files.write('done.txt', 'done\n')
    await fork.index.commit('done')
    await fork.terminal('echo wip > wip.txt')
    expect(fork.uncommitted).toBe(false)
    await expect(ws.merge('worker')).rejects.toThrow("uncommitted ws-git work on 'worker'")
    expect(await ws.files.exists('done.txt')).toBe(false)
    await fork.index.commit('wip')
    expect((await ws.merge('worker')).merged).toBe(true)
    expect(await read(ws, 'wip.txt')).toBe('wip\n')
    await fork.close()
    await ws.close()
  })

  it('is refused while a source has a merge of its own outstanding', async () => {
    const ws = await open()
    await put(ws, '/workspace/doc.txt', 'a\nb\n')
    await ws.index.commit('base')
    const mid = await ws.fork('mid')
    const leaf = await mid.fork('leaf')
    await put(leaf, '/workspace/doc.txt', 'a\nLEAF\n')
    await leaf.index.commit('leaf')
    await put(mid, '/workspace/doc.txt', 'a\nMID\n')
    await mid.index.commit('mid')
    expect((await mid.merge('leaf')).conflicts).toEqual(['/workspace/doc.txt'])
    await expect(ws.merge('mid')).rejects.toThrow("'mid' has an unresolved merge from leaf")
    await leaf.close()
    await mid.close()
    await ws.close()
  })
})

describe('ws.revert', () => {
  it('undoes the last commit as a new one, keeping it', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\n')
    const first = await ws.index.commit('first')
    await ws.files.write('a.txt', 'two\n')
    const second = await ws.index.commit('second')
    const out = await ws.revert(second)
    expect(out).toMatchObject({ merged: true, conflicts: [], autoMerged: ['/workspace/a.txt'] })
    expect(await read(ws, 'a.txt')).toBe('one\n')
    const log = (await ws.index.log()).map((c) => c.hash)
    expect(log).toEqual([out.commit, second, first])
    const entry = await ws.store.repo.getCommit(out.commit as string)
    expect(entry.info).toMatchObject({ reverted: second, message: 'Revert "second"' })
    expect(entry.parents).not.toEqual([second])
    await ws.close()
  })

  it('leaves later work alone', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\ntwo\nthree\n')
    await ws.index.commit('first')
    await ws.files.write('a.txt', 'one\nTWO\nthree\n')
    const second = await ws.index.commit('second')
    await ws.files.write('a.txt', 'one\nTWO\nTHREE\n')
    await ws.index.commit('third')
    expect((await ws.revert(second)).conflicts).toEqual([])
    expect(await read(ws, 'a.txt')).toBe('one\ntwo\nTHREE\n')
    await ws.close()
  })

  it('leaves markers and an outstanding merge where later work overlaps', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\ntwo\nthree\n')
    await ws.index.commit('first')
    await ws.files.write('a.txt', 'one\nTWO\nthree\n')
    const second = await ws.index.commit('second')
    await ws.files.write('a.txt', 'one\nLATER\nthree\n')
    await ws.index.commit('third')
    const out = await ws.revert(second)
    expect(out).toMatchObject({ merged: true, conflicts: ['/workspace/a.txt'] })
    const status = await ws.index.status()
    expect(status.mergeSource).toContain(second.slice(0, 7))
    expect(status.mergeUnresolved).toEqual(['/workspace/a.txt'])
    await ws.files.write('a.txt', 'resolved\n')
    await ws.index.commit('resolved')
    expect((await ws.index.status()).mergeSource).toBeNull()
    await ws.close()
  })

  it('undoes a first commit against nothing', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\ntwo\nthree\n')
    const first = await ws.index.commit('first')
    await ws.files.write('a.txt', 'one\nEDITED\nthree\n')
    await ws.index.commit('second')
    const out = await ws.revert(first)
    expect(out).toMatchObject({ merged: true, conflicts: ['/workspace/a.txt'] })
    expect(await read(ws, 'a.txt')).toContain('<<<<<<< ')
    await ws.close()
  })

  it('takes a merge back to ours', async () => {
    const ws = await open()
    await ws.files.write('base.txt', 'base\n')
    await ws.index.commit('seed')
    const child = await ws.fork('child')
    await child.files.write('theirs.txt', 'theirs\n')
    await child.index.commit('child work')
    await ws.files.write('mine.txt', 'mine\n')
    await ws.index.commit('my work')
    const merge = await ws.merge('child')
    expect(await ws.files.exists('theirs.txt')).toBe(true)
    const out = await ws.revert(merge.commit as string)
    expect(out).toMatchObject({ merged: true, conflicts: [] })
    expect(await ws.files.exists('theirs.txt')).toBe(false)
    expect(await read(ws, 'mine.txt')).toBe('mine\n')
    expect(await read(ws, 'base.txt')).toBe('base\n')
    await child.close()
    await ws.close()
  })

  it('says so when there is nothing to undo', async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\n')
    const first = await ws.index.commit('first')
    await ws.revert(first)
    const head = await ws.index.head()
    expect(await ws.revert(first)).toEqual({
      merged: false,
      commit: null,
      conflicts: [],
      autoMerged: [],
    })
    expect(await ws.index.head()).toBe(head)
    await ws.close()
  })

  it("refuses a commit that isn't there", async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\n')
    await ws.index.commit('first')
    await expect(ws.revert('0'.repeat(40))).rejects.toThrow(UnknownRefError)
    await ws.close()
  })
})

describe('ws.cherryPick', () => {
  it("brings one commit of a delegate's, and nothing around it", async () => {
    const ws = await open()
    await ws.files.write('base.txt', 'base\n')
    await ws.index.commit('seed')
    const child = await ws.fork('child')
    await child.files.write('one.txt', 'one\n')
    await child.index.commit('one')
    await child.files.write('two.txt', 'two\n')
    const wanted = await child.index.commit('two')
    await child.files.write('three.txt', 'three\n')
    await child.index.commit('three')
    const out = await ws.cherryPick(`child@${wanted}`)
    expect(out).toMatchObject({ merged: true, conflicts: [], autoMerged: ['/workspace/two.txt'] })
    expect(await read(ws, 'two.txt')).toBe('two\n')
    expect(await ws.files.exists('one.txt')).toBe(false)
    expect(await ws.files.exists('three.txt')).toBe(false)
    const entry = await ws.store.repo.getCommit(out.commit as string)
    expect(entry.info).toMatchObject({ pickedFrom: `child@${wanted}`, message: 'two' })
    expect(await ws.cherryPick(`child@${wanted.slice(0, 7)}`)).toMatchObject({ merged: false })
    await child.close()
    await ws.close()
  })

  it("brings only a delegate's own work from its first commit", async () => {
    const ws = await open()
    await ws.files.write('base.txt', 'base\n')
    await ws.index.commit('seed')
    const child = await ws.fork('child')
    await child.files.write('from_child.txt', 'child\n')
    const wanted = await child.index.commit('child work')
    await ws.files.write('base.txt', 'base, edited here\n')
    await ws.index.commit('my work')
    const out = await ws.cherryPick(`child@${wanted}`)
    expect(out).toMatchObject({
      merged: true,
      conflicts: [],
      autoMerged: ['/workspace/from_child.txt'],
    })
    expect(await read(ws, 'base.txt')).toBe('base, edited here\n')
    await child.close()
    await ws.close()
  })

  it('measures from the fork point when the parent never used ws-git', async () => {
    const ws = await open()
    await ws.files.write('kept.txt', 'kept\n')
    await ws.files.write('gone.txt', 'gone\n')
    const child = await ws.fork('child')
    await child.files.write('kept.txt', 'kept, by the child\n')
    const wanted = await child.index.commit('child edit')
    await ws.files.remove('gone.txt')
    const out = await ws.cherryPick(`child@${wanted}`)
    expect(out).toMatchObject({ merged: true, conflicts: [], autoMerged: ['/workspace/kept.txt'] })
    expect(await read(ws, 'kept.txt')).toBe('kept, by the child\n')
    expect(await ws.files.exists('gone.txt')).toBe(false)
    await child.close()
    await ws.close()
  })

  it('lands overlapping work with markers', async () => {
    const ws = await open()
    await ws.files.write('shared.txt', 'one\ntwo\nthree\n')
    await ws.index.commit('seed')
    const child = await ws.fork('child')
    await child.files.write('shared.txt', 'one\nCHILD\nthree\n')
    const wanted = await child.index.commit('child edit')
    await ws.files.write('shared.txt', 'one\nMINE\nthree\n')
    await ws.index.commit('my edit')
    const out = await ws.cherryPick(`child@${wanted}`)
    expect(out).toMatchObject({ merged: true, conflicts: ['/workspace/shared.txt'] })
    const body = await read(ws, 'shared.txt')
    expect(body).toContain('<<<<<<< ')
    expect(body).toContain('CHILD')
    expect(body).toContain('MINE')
    expect((await ws.index.status()).mergeSource).toBe(`child@${wanted.slice(0, 7)}`)
    await child.close()
    await ws.close()
  })

  it("refuses a commit the named session doesn't hold, or no session", async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\n')
    await ws.index.commit('seed')
    const peer = await ws.fork('peer')
    const child = await ws.fork('child')
    await peer.files.write('peer.txt', 'peer\n')
    const elsewhere = await peer.index.commit('peer work')
    await child.files.write('child.txt', 'child\n')
    await child.index.commit('child work')
    await expect(ws.cherryPick(`child@${elsewhere}`)).rejects.toThrow(UnknownRefError)
    await expect(ws.cherryPick(`child@${elsewhere.slice(0, 7)}`)).rejects.toThrow('child')
    await expect(ws.cherryPick(`peerless@${elsewhere}`)).rejects.toThrow(UnknownSessionError)
    await expect(ws.cherryPick('child')).rejects.toThrow('session@commit')
    expect(await ws.files.exists('peer.txt')).toBe(false)
    expect((await ws.cherryPick(`peer@${elsewhere}`)).merged).toBe(true)
    expect(await read(ws, 'peer.txt')).toBe('peer\n')
    await child.close()
    await peer.close()
    await ws.close()
  })
})

describe('revert and cherry-pick', () => {
  it("refuse the agent's uncommitted work", async () => {
    const ws = await open()
    await ws.files.write('a.txt', 'one\n')
    const first = await ws.index.commit('first')
    const child = await ws.fork('child')
    await child.files.write('b.txt', 'two\n')
    const theirs = await child.index.commit('child work')
    await ws.terminal('echo wip > /workspace/wip.txt')
    expect(ws.uncommitted).toBe(false)
    await expect(ws.revert(first)).rejects.toThrow('uncommitted ws-git work')
    await expect(ws.cherryPick(`child@${theirs}`)).rejects.toThrow('uncommitted ws-git work')
    await child.close()
    await ws.close()
  })

  it('refuse while a merge is outstanding', async () => {
    const ws = await open()
    await ws.files.write('shared.txt', 'one\ntwo\nthree\n')
    const first = await ws.index.commit('seed')
    const child = await ws.fork('child')
    await child.files.write('shared.txt', 'one\nCHILD\nthree\n')
    const picked = await child.index.commit('child edit')
    await ws.files.write('shared.txt', 'one\nMINE\nthree\n')
    await ws.index.commit('my edit')
    expect((await ws.merge('child')).conflicts).not.toEqual([])
    await expect(ws.revert(first)).rejects.toThrow('unresolved merge')
    await expect(ws.cherryPick(`child@${picked}`)).rejects.toThrow('unresolved merge')
    await ws.files.write('shared.txt', 'resolved\n')
    await ws.index.commit('resolved')
    expect((await ws.revert(first)).merged).toBeDefined()
    await child.close()
    await ws.close()
  })
})
