#!/usr/bin/env node
/**
 * Copy agex's shape corpus (its exported JSON, and the schemas) into
 * src/conformance/, from an agex checkout's origin/main, and regenerate
 * the corpus index: task scenarios and code scenarios (`code-...`), each
 * by name.
 *
 * Usage: node scripts/sync-shape-corpus.mjs PATH/TO/agex [ref]
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [repo, ref = 'origin/main'] = process.argv.slice(2)
if (repo === undefined) {
  console.error('usage: node scripts/sync-shape-corpus.mjs PATH/TO/agex [ref]')
  process.exit(2)
}
const here = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'conformance')
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })

const corpus = join(here, 'corpus')
rmSync(corpus, { recursive: true, force: true })
mkdirSync(corpus)
for (const path of git('ls-tree', '--name-only', `${ref}:agex/conformance/json/`).split('\n')) {
  if (path.endsWith('.json')) {
    writeFileSync(join(corpus, path), git('show', `${ref}:agex/conformance/json/${path}`))
  }
}
for (const name of ['task_scenario', 'code_scenario']) {
  const schema = `${name}.schema.json`
  writeFileSync(join(here, schema), git('show', `${ref}:agex/conformance/schema/${schema}`))
}

const files = readdirSync(corpus)
  .filter((f) => f.endsWith('.json'))
  .sort()
const ident = (f) => f.replace(/\.json$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const code = files.filter((f) => f.startsWith('code-'))
const tasks = files.filter((f) => !f.startsWith('code-'))
const commit = git('rev-parse', '--short', ref).trim()
writeFileSync(
  join(corpus, 'index.ts'),
  [
    `// Generated by scripts/sync-shape-corpus.mjs from agex ${commit}; do not edit.`,
    "import type { CodeScenario, TaskScenario } from '../shape'",
    ...files.map((f) => `import ${ident(f)} from './${f}'`),
    '',
    '/** The agex commit the corpus was synced from. */',
    `export const AGEX_COMMIT = '${commit}'`,
    '',
    "/** agex's task scenarios, by name. */",
    'export const TASK_SCENARIOS: readonly TaskScenario[] = [',
    ...tasks.map((f) => `  ${ident(f)} as TaskScenario,`),
    ']',
    '',
    "/** agex's scenarios of tasks agent code defines, by name. */",
    'export const CODE_SCENARIOS: readonly CodeScenario[] = [',
    ...code.map((f) => `  ${ident(f)} as CodeScenario,`),
    ']',
    '',
  ].join('\n'),
)
console.log(`synced ${tasks.length} task and ${code.length} code scenarios from agex ${commit}`)
