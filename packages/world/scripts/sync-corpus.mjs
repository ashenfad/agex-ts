#!/usr/bin/env node
/**
 * Copy nontainer's harness corpus (its exported JSON, and the schemas)
 * into src/conformance/, from a nontainer checkout's origin/main, and
 * regenerate the corpus index. Its ws-git script corpus goes to
 * tests/wsgit-corpus/, for the ws-git port's own test, and its trace
 * corpus to tests/traces-corpus/, for the trace renderer's.
 *
 * Usage: node scripts/sync-corpus.mjs PATH/TO/nontainer [ref]
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [repo, ref = 'origin/main'] = process.argv.slice(2)
if (repo === undefined) {
  console.error('usage: node scripts/sync-corpus.mjs PATH/TO/nontainer [ref]')
  process.exit(2)
}
const here = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'conformance')
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })

const corpus = join(here, 'corpus')
rmSync(corpus, { recursive: true, force: true })
mkdirSync(corpus)
for (const path of git(
  'ls-tree',
  '--name-only',
  `${ref}:nontainer/conformance/harness/json/`,
).split('\n')) {
  if (path.endsWith('.json')) {
    writeFileSync(
      join(corpus, path),
      git('show', `${ref}:nontainer/conformance/harness/json/${path}`),
    )
  }
}
for (const name of ['scenario', 'turn_event']) {
  const schema = `${name}.schema.json`
  writeFileSync(join(here, schema), git('show', `${ref}:nontainer/conformance/schema/${schema}`))
}

// The index, in tier order (a scenario's lowest tier), then by name.
const files = readdirSync(corpus)
  .filter((f) => f.endsWith('.json'))
  .map((f) => ({ f, tier: Math.min(...JSON.parse(readFileSync(join(corpus, f), 'utf8')).tiers) }))
  .sort((a, b) => a.tier - b.tier || a.f.localeCompare(b.f))
const ident = (f) => f.replace(/\.json$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const commit = git('rev-parse', '--short', ref).trim()
writeFileSync(
  join(corpus, 'index.ts'),
  [
    `// Generated by scripts/sync-corpus.mjs from nontainer ${commit}; do not edit.`,
    "import type { Scenario } from '../scenario'",
    ...files.map(({ f }) => `import ${ident(f)} from './${f}'`),
    '',
    "/** nontainer's harness corpus, in tier order. */",
    'export const SCENARIOS: readonly Scenario[] = [',
    ...files.map(({ f }) => `  ${ident(f)} as Scenario,`),
    ']',
    '',
  ].join('\n'),
)
console.log(`synced ${files.length} scenarios from nontainer ${commit}`)

// The ws-git scripts, recorded by nontainer: what the TS port must print.
const scripts = join(here, '..', '..', 'tests', 'wsgit-corpus')
rmSync(scripts, { recursive: true, force: true })
mkdirSync(scripts)
for (const path of git('ls-tree', '--name-only', `${ref}:nontainer/conformance/wsgit/json/`).split(
  '\n',
)) {
  if (path.endsWith('.json')) {
    writeFileSync(
      join(scripts, path),
      git('show', `${ref}:nontainer/conformance/wsgit/json/${path}`),
    )
  }
}

// The trace cases, recorded by nontainer: every file a trace renders.
const traces = join(here, '..', '..', 'tests', 'traces-corpus')
rmSync(traces, { recursive: true, force: true })
mkdirSync(traces)
for (const path of git('ls-tree', '--name-only', `${ref}:nontainer/conformance/traces/json/`).split(
  '\n',
)) {
  if (path.endsWith('.json')) {
    writeFileSync(
      join(traces, path),
      git('show', `${ref}:nontainer/conformance/traces/json/${path}`),
    )
  }
}
